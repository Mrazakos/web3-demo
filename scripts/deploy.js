const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  const [deployer] = await hre.ethers.getSigners();
  const balance = await hre.ethers.provider.getBalance(deployer.address);

  console.log("==================================================");
  console.log("🚀 Deploying SimpleStorage Smart Contract");
  console.log(`👤 Deployer Account: ${deployer.address}`);
  console.log(`💰 Account Balance:  ${hre.ethers.formatEther(balance)} ETH`);
  console.log("==================================================");

  const initialValue = "Hello, Hardhat & Web3!";
  const SimpleStorageFactory = await hre.ethers.getContractFactory("SimpleStorage");
  const simpleStorage = await SimpleStorageFactory.deploy(initialValue);

  await simpleStorage.waitForDeployment();
  const contractAddress = await simpleStorage.getAddress();

  console.log(`✅ SimpleStorage deployed to: ${contractAddress}`);
  console.log(`📝 Initial stored value:     "${initialValue}"`);

  // Export contract address and ABI to frontend
  const frontendSrcDir = path.join(__dirname, "..", "frontend", "src");
  if (!fs.existsSync(frontendSrcDir)) {
    fs.mkdirSync(frontendSrcDir, { recursive: true });
  }

  // Get artifact for ABI
  const artifact = await hre.artifacts.readArtifact("SimpleStorage");

  const contractDataContent = `// Automatically generated by scripts/deploy.js - DO NOT EDIT MANUALLY
export const CONTRACT_ADDRESS = "${contractAddress}";

export const CONTRACT_ABI = ${JSON.stringify(artifact.abi, null, 2)};
`;

  const outputPath = path.join(frontendSrcDir, "contractData.js");
  fs.writeFileSync(outputPath, contractDataContent);

  console.log(`📦 Saved contract address & ABI to: ${outputPath}`);
  console.log("==================================================");
}

main().catch((error) => {
  console.error("❌ Deployment failed:", error);
  process.exitCode = 1;
});
